-- DineFlow: Restaurant Order and Billing System
-- This script uses ONLY the five core tables named in the supplied project brief:
-- menu_items, restaurant_tables, orders, order_items, bills.
-- Run the complete script in Supabase SQL Editor.

begin;

-- 1. Core tables
create table if not exists public.menu_items (
  id bigint generated by default as identity primary key,
  item_name text not null unique,
  category text,
  price numeric(10,2) not null check (price > 0),
  is_available boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.restaurant_tables (
  id bigint generated by default as identity primary key,
  table_number integer not null unique check (table_number > 0),
  table_status text not null default 'available'
    check (table_status in ('available', 'occupied'))
);

create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  table_id bigint not null references public.restaurant_tables(id),
  order_status text not null default 'open'
    check (order_status in ('open', 'closed', 'cancelled')),
  ordered_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(id) on delete cascade,
  menu_item_id bigint not null references public.menu_items(id),
  quantity integer not null check (quantity > 0),
  unit_price numeric(10,2) not null check (unit_price >= 0),
  line_total numeric(12,2) generated always as (quantity * unit_price) stored
);

create table if not exists public.bills (
  id bigint generated by default as identity primary key,
  order_id bigint not null unique references public.orders(id) on delete cascade,
  total_amount numeric(12,2) not null default 0 check (total_amount >= 0),
  bill_status text not null default 'open'
    check (bill_status in ('open', 'paid')),
  created_at timestamptz not null default now(),
  closed_at timestamptz
);

create index if not exists idx_orders_table_id on public.orders(table_id);
create index if not exists idx_order_items_order_id on public.order_items(order_id);
create index if not exists idx_order_items_menu_item_id on public.order_items(menu_item_id);
create index if not exists idx_bills_status on public.bills(bill_status);

-- 2. When an order is opened, create its bill and occupy its restaurant table.
create or replace function public.prepare_new_order()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  update public.restaurant_tables
  set table_status = 'occupied'
  where id = new.table_id and table_status = 'available';

  if not found then
    raise exception 'This restaurant table is not available.';
  end if;

  insert into public.bills(order_id, total_amount, bill_status)
  values (new.id, 0, 'open');

  return new;
end;
$$;

drop trigger if exists trg_prepare_new_order on public.orders;
create trigger trg_prepare_new_order
after insert on public.orders
for each row execute function public.prepare_new_order();

-- 3. BEFORE INSERT: copy the current menu price into the order item.
create or replace function public.copy_current_menu_price()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  current_price numeric(10,2);
begin
  select price into current_price
  from public.menu_items
  where id = new.menu_item_id and is_available = true;

  if current_price is null then
    raise exception 'Menu item does not exist or is unavailable.';
  end if;

  new.unit_price := current_price;
  return new;
end;
$$;

drop trigger if exists trg_copy_menu_price on public.order_items;
create trigger trg_copy_menu_price
before insert on public.order_items
for each row execute function public.copy_current_menu_price();

-- 4. AFTER INSERT/UPDATE/DELETE: keep the related open bill total correct.
-- AFTER INSERT implements the trigger idea in the supplied brief.
create or replace function public.refresh_bill_total_from_order_items()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  affected_order_id bigint;
begin
  if tg_op = 'DELETE' then
    affected_order_id := old.order_id;
  else
    affected_order_id := new.order_id;
  end if;

  update public.bills b
  set total_amount = coalesce((
    select sum(oi.line_total)
    from public.order_items oi
    where oi.order_id = affected_order_id
  ), 0)
  where b.order_id = affected_order_id
    and b.bill_status = 'open';

  if tg_op = 'DELETE' then return old; else return new; end if;
end;
$$;

drop trigger if exists trg_update_bill_total_insert on public.order_items;
create trigger trg_update_bill_total_insert
after insert on public.order_items
for each row execute function public.refresh_bill_total_from_order_items();

drop trigger if exists trg_update_bill_total_update on public.order_items;
create trigger trg_update_bill_total_update
after update of quantity, menu_item_id on public.order_items
for each row execute function public.refresh_bill_total_from_order_items();

drop trigger if exists trg_update_bill_total_delete on public.order_items;
create trigger trg_update_bill_total_delete
after delete on public.order_items
for each row execute function public.refresh_bill_total_from_order_items();

-- 5. Close a bill and free its table atomically.
-- Calling this RPC is one database transaction: either all updates succeed or none do.
create or replace function public.close_bill(p_order_id bigint)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  target_table_id bigint;
  target_bill_status text;
begin
  select o.table_id, b.bill_status
    into target_table_id, target_bill_status
  from public.orders o
  join public.bills b on b.order_id = o.id
  where o.id = p_order_id
  for update of o, b;

  if target_table_id is null then
    raise exception 'Order or bill was not found.';
  end if;

  if target_bill_status <> 'open' then
    raise exception 'This bill is already closed.';
  end if;

  update public.bills
  set bill_status = 'paid', closed_at = now()
  where order_id = p_order_id;

  update public.orders
  set order_status = 'closed'
  where id = p_order_id;

  update public.restaurant_tables
  set table_status = 'available'
  where id = target_table_id;
end;
$$;

-- 6. Bill details view: items, quantity and amount per table.
create or replace view public.bill_details as
select
  b.id as bill_id,
  o.id as order_id,
  rt.table_number,
  mi.item_name,
  oi.quantity,
  oi.unit_price,
  oi.line_total as amount,
  b.total_amount as bill_total,
  b.bill_status,
  o.ordered_at
from public.bills b
join public.orders o on o.id = b.order_id
join public.restaurant_tables rt on rt.id = o.table_id
join public.order_items oi on oi.order_id = o.id
join public.menu_items mi on mi.id = oi.menu_item_id;

-- 7. Report views requested in the supplied brief.
create or replace view public.best_selling_dishes as
select
  mi.id as menu_item_id,
  mi.item_name,
  sum(oi.quantity)::bigint as quantity_sold,
  sum(oi.line_total)::numeric(12,2) as sales_amount
from public.order_items oi
join public.menu_items mi on mi.id = oi.menu_item_id
join public.orders o on o.id = oi.order_id
join public.bills b on b.order_id = o.id
where b.bill_status = 'paid'
group by mi.id, mi.item_name
order by quantity_sold desc, mi.item_name;

create or replace view public.revenue_by_day as
select
  (b.closed_at at time zone 'Asia/Kolkata')::date as sale_day,
  sum(b.total_amount)::numeric(12,2) as revenue
from public.bills b
where b.bill_status = 'paid' and b.closed_at is not null
group by (b.closed_at at time zone 'Asia/Kolkata')::date
order by sale_day desc;

create or replace view public.busiest_hour as
select
  extract(hour from (o.ordered_at at time zone 'Asia/Kolkata'))::integer as order_hour,
  count(*)::bigint as order_count
from public.orders o
group by extract(hour from (o.ordered_at at time zone 'Asia/Kolkata'))
order by order_count desc, order_hour;

